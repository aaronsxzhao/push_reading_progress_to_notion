// The runtime has only one dependency: Obsidian's own cross-platform API.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const core = fs.readFileSync(path.join(root, 'src/core.js'), 'utf8');
const main = fs.readFileSync(path.join(root, 'src/main.js'), 'utf8');
const bundled = main.replace("const Core = require('./core');", `const Core = (() => { const module = { exports: {} };\n${core}\nreturn module.exports; })();`);
fs.writeFileSync(path.join(root, 'main.js'), '// Generated by npm run build. Edit src/ instead.\n' + bundled);
console.log('Built main.js (no Node.js APIs or external packages in runtime).');
